def main():
    z = zipfile.ZipFile(io.BytesIO(base64.b64decode("".join(DATOS.split()))))
    # 1) calcular TODOS los parches en memoria; si uno falla no se toca nada
    textos, cambios, errores = {}, {}, []
    for ruta_rel, ancla, antes, marca, despues in PARCHES:
        ruta = os.path.join(RAIZ, *ruta_rel.split("/"))
        if not os.path.exists(ruta):
            errores.append("No existe " + ruta_rel); continue
        if ruta_rel not in textos:
            with open(ruta, "rb") as f:
                crudo = f.read()
            textos[ruta_rel] = (crudo, "\r\n" in crudo.decode("utf-8"), crudo.decode("utf-8").replace("\r\n", "\n"))
        crudo, crlf, t = textos[ruta_rel]
        if marca in t:
            continue   # ya aplicado
        if t.count(ancla) != 1:
            errores.append("%s: no encuentro el punto de inserción (%d coincidencias). ¿Falta algún instalador anterior?" % (ruta_rel, t.count(ancla))); continue
        if despues == "BOTON":
            nuevo = BOTON + "\n\n            " + ancla
        elif antes is not None:
            nuevo = antes + ancla
        else:
            nuevo = ancla + despues
        textos[ruta_rel] = (crudo, crlf, t.replace(ancla, nuevo, 1))
        cambios[ruta_rel] = True
    if errores:
        print("NO SE HA CAMBIADO NADA:")
        for e in errores: print("  -", e)
        sys.exit(1)

    # 2) escribir
    for ruta_rel in cambios:
        crudo, crlf, t = textos[ruta_rel]
        ruta = os.path.join(RAIZ, *ruta_rel.split("/"))
        with open(ruta + ".bak", "wb") as f:
            f.write(crudo)
        with open(ruta, "wb") as f:
            f.write((t.replace("\n", "\r\n") if crlf else t).encode("utf-8"))
        print("  OK   parcheado:", ruta_rel)
    for nombre in z.namelist():
        nuevo = z.read(nombre)
        ruta = os.path.join(RAIZ, *nombre.split("/"))
        os.makedirs(os.path.dirname(ruta), exist_ok=True)
        if os.path.exists(ruta):
            with open(ruta, "rb") as f:
                actual = f.read()
            if actual == nuevo:
                continue
            with open(ruta + ".bak", "wb") as f:
                f.write(actual)
        with open(ruta, "wb") as f:
            f.write(nuevo)
        print("  OK   copiado:  ", nombre)
    print("Listo. Reinicia servidor_datos.py y Streamlit; el botón «Backtest» está en la barra superior del gráfico.")


main()
