def main():
    z = zipfile.ZipFile(io.BytesIO(base64.b64decode("".join(DATOS.split()))))
    nuevos = cambiados = iguales = 0
    for nombre in z.namelist():
        contenido = z.read(nombre)
        ruta = os.path.join(RAIZ, *nombre.split("/"))
        os.makedirs(os.path.dirname(ruta), exist_ok=True)
        if os.path.exists(ruta):
            with open(ruta, "rb") as f:
                actual = f.read()
            if actual == contenido:
                iguales += 1
                continue
            cambiados += 1
            etiqueta = "reemplazado"
        else:
            nuevos += 1
            etiqueta = "nuevo      "
        with open(ruta, "wb") as f:
            f.write(contenido)
        print("  OK  %s %s" % (etiqueta, nombre))
    borrados = 0
    for nombre in BORRAR:
        ruta = os.path.join(RAIZ, *nombre.split("/"))
        if os.path.isfile(ruta):
            os.remove(ruta)
            borrados += 1
            print("  OK  borrado     %s (lo reemplaza su paquete)" % nombre)
    gi = os.path.join(RAIZ, ".gitignore")
    texto = open(gi, encoding="utf-8").read() if os.path.exists(gi) else ""
    if "*.bak" not in texto.split():
        with open(gi, "a", encoding="utf-8") as f:
            f.write(("" if texto.endswith("\n") or not texto else "\n") + "\n# Copias de respaldo manuales\n*.bak\n")
        print("  OK  .gitignore: agregado *.bak")
    print("\nNuevos: %d · reemplazados: %d · borrados: %d · ya estaban iguales: %d  (sin copias .bak)"
          % (nuevos, cambiados, borrados, iguales))
    print("Listo. Reinicia Streamlit.")


main()
