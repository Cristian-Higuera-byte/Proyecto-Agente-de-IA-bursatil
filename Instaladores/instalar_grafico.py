def main():
    if not os.path.isfile("app.py") or not os.path.isdir("components"):
        sys.exit("Ejecuta este archivo desde la RAIZ del proyecto (donde estan app.py y la carpeta components).")
    z = zipfile.ZipFile(io.BytesIO(base64.b64decode("".join(ZIP_B64.split()))))
    nuevos = actualizados = 0
    for nombre in z.namelist():
        destino = nombre.replace("/", os.sep)
        os.makedirs(os.path.dirname(destino), exist_ok=True)
        if os.path.exists(destino):
            shutil.copy2(destino, destino + ".bak")
            actualizados += 1
        else:
            nuevos += 1
        with open(destino, "wb") as f:
            f.write(z.read(nombre))
    print(f"Listo: {nuevos} archivos nuevos y {actualizados} reemplazados (con copia .bak).")
    print("Ahora reinicia Streamlit. Debe existir la carpeta components/grafico/.")


