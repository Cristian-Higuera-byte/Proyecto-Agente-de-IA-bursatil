    (E + "esqueleto.html", "@@js/25_dibujo_pincel_resaltador_flechas.js", None, "@@js/26_dibujo_extra_base.js",
     "\n@@js/26_dibujo_extra_base.js\n@@js/27_dibujo_extra_lineas_patrones.js\n@@js/28_dibujo_extra_proyeccion_figuras_texto.js"),
