def sin_conflictos(texto):
    salida, estado = [], 0
    for ln in texto.splitlines(keepends=True):
        s = ln.rstrip("\r\n")
        if s.startswith("<<<<<<<"): estado = 1; continue
        if s.startswith("=======") and estado == 1: estado = 2; continue
        if s.startswith(">>>>>>>") and estado == 2: estado = 0; continue
        if estado == 1: continue
        salida.append(ln)
    if estado != 0:
        return None
    return "".join(salida)


def main():
    z = zipfile.ZipFile(io.BytesIO(base64.b64decode("".join(DATOS.split()))))
    copiados = iguales = 0
    for nombre in z.namelist():
        nuevo = z.read(nombre)
        ruta = os.path.join(RAIZ, *nombre.split("/"))
        os.makedirs(os.path.dirname(ruta), exist_ok=True)
        if os.path.exists(ruta):
            with open(ruta, "rb") as f:
                actual = f.read()
            if actual == nuevo:
                iguales += 1
                continue
            with open(ruta + ".bak", "wb") as f:
                f.write(actual)
        with open(ruta, "wb") as f:
            f.write(nuevo)
        copiados += 1
        print("  OK  ", nombre)
    print("Archivos copiados: %d (ya iguales: %d)" % (copiados, iguales))

    for rel in CONFLICTOS:
        ruta = os.path.join(RAIZ, *rel.split("/"))
        if not os.path.exists(ruta):
            print("  --   no existe", rel); continue
        with open(ruta, "rb") as f:
            crudo = f.read()
        texto = crudo.decode("utf-8")
        if "<<<<<<<" not in texto:
            print("  --   sin conflictos:", rel); continue
        limpio = sin_conflictos(texto)
        if limpio is None:
            print("  !!   marcadores incompletos, revisa a mano:", rel); continue
        with open(ruta + ".bak", "wb") as f:
            f.write(crudo)
        with open(ruta, "wb") as f:
            f.write(limpio.encode("utf-8"))
        print("  OK   conflicto resuelto:", rel)
    print("Listo. Reinicia Streamlit (y servidor_datos.py si estaba abierto).")


main()
