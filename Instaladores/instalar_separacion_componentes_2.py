def main():
    z = zipfile.ZipFile(io.BytesIO(base64.b64decode("".join(DATOS.split()))))
    nuevos = cambiados = iguales = 0
    for nombre in z.namelist():
        contenido = z.read(nombre)
        ruta = os.path.join(RAIZ, *nombre.split("/"))
        os.makedirs(os.path.dirname(ruta), exist_ok=True)
        if os.path.exists(ruta):
            with open(ruta, "rb") as f:
                if f.read() == contenido:
                    iguales += 1
                    continue
            etiqueta = "reemplazado"
            cambiados += 1
        else:
            etiqueta = "nuevo      "
            nuevos += 1
        with open(ruta, "wb") as f:
            f.write(contenido)
        print("  OK  %s %s" % (etiqueta, nombre))
    print("\nNuevos: %d · reemplazados: %d · ya estaban iguales: %d  (sin copias .bak)" % (nuevos, cambiados, iguales))
    print("Listo. Reinicia Streamlit; todo debe verse exactamente igual que antes.")


main()
